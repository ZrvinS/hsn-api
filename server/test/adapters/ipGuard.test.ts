import { describe, expect, it } from 'vitest';
import { isBlockedAddress } from '../../src/adapters/ipGuard.js';

describe('isBlockedAddress (SEC-34)', () => {
  it.each([
    '127.0.0.1', '127.255.255.254', '10.0.0.1', '10.255.255.255', '172.16.0.1', '172.31.255.255', '192.168.1.1',
    '169.254.169.254', '169.254.0.1', '100.64.0.1', '100.127.255.255', '0.0.0.0', '0.1.2.3', '224.0.0.1', '239.255.255.250',
    '255.255.255.255', '240.0.0.1', '192.0.2.10', '198.18.0.1', '203.0.113.5',
    '::', '::1', 'fc00::1', 'fd12:3456::1', 'fe80::1', 'fe80::1%eth0', 'ff02::1', 'fec0::1',
    '::ffff:127.0.0.1', '::ffff:169.254.169.254', '::ffff:7f00:1', '::127.0.0.1', '64:ff9b::7f00:1', '2002:7f00:1::', '2001:0:4136:e378::1', '2001:db8::1',
    '198.18.0.1', '198.19.255.255', '240.0.0.1', '255.255.255.254', '2001:10::1', '2001:2::1', '2001:20::1', '3fff::1', '64:ff9b:1::7f00:1',
    'localhost', 'not-an-ip', '', '1.2.3', '256.1.1.1',
  ])('blocks %s', (ip) => {
    expect(isBlockedAddress(ip)).toBe(true);
  });

  it.each(['8.8.8.8', '1.1.1.1', '151.101.1.69', '172.32.0.1', '100.128.0.1', '2606:4700:4700::1111', '2a00:1450:4001:80b::200e'])('allows public %s', (ip) => {
    expect(isBlockedAddress(ip)).toBe(false);
  });
});
